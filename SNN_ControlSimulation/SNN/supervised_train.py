def load_stats(data_dir: str) -> dict:
    stats_path = os.path.join(data_dir, 'dataset_stats.npz')
    if not os.path.exists(stats_path):
        raise FileNotFoundError(
            f"No se encontró '{stats_path}'.\n"
            f"Ejecuta primero: python3 compute_dataset_stats.py"
        )
    s = np.load(stats_path)
    return {k: s[k].astype(np.float32) for k in s.files}


class EpisodeDataset(Dataset):
    def __init__(self, episode_pairs: list, input_size: int, stats: dict):
        self.pairs      = episode_pairs
        self.input_size = input_size
        self.stats      = stats

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, idx):
        ev_path, st_path = self.pairs[idx]

        # Cargar el episodio completo
        with h5py.File(ev_path, 'r') as f:
            events = np.array(f['events_matrix'][()], dtype=np.float32)

        # Transposición física correcta: (T, C, H, W)
        events = np.transpose(events, (0, 3, 2, 1))

        # Reducción de resolución
        T_len, C, H, W = events.shape
        if H != self.input_size or W != self.input_size:
            t = torch.from_numpy(events).reshape(T_len * C, 1, H, W)
            t = F.interpolate(t, size=(self.input_size, self.input_size), mode='area')
            events = t.reshape(T_len, C, self.input_size, self.input_size).numpy()

        # Cargar estados
        st_data = scipy.io.loadmat(st_path)
        torques = st_data['torque_pid'].astype(np.float32)

        torques = torques - self.stats['torque_mean']
        torques = torques / self.stats['torque_peak']

        return torch.from_numpy(events), torch.from_numpy(torques)


