def run_epoch(model, loader, optimizer, criterion, cfg, device, train: bool):
    model.train(train)
    total_loss = 0.0
    batches = 0
    phase = "Train" if train else "Val  "

    pbar = tqdm(loader, desc=f"  {phase}", unit="batch", leave=False)

    with torch.set_grad_enabled(train):
        for b_events, b_torques in pbar:
            # Ahora la forma es (B, Tiempo_Total, C, H, W)
            B, T_total, C, H, W = b_events.shape
            state = model.init_state(batch_size=B, device=device)
            d_shift = CONFIG['d_shift'] 
            seq = cfg['seq_length']

            if train:
                optimizer.zero_grad()   # un solo zero_grad por episodio

            accumulated_chunks = []

            for start in range(0, T_total - d_shift, seq):
                end = min(start + seq, T_total - d_shift)
                if end - start < 10: break # Evitar ventanas muy pequeñas al final

                # 3. HEREDAMOS LA MEMORIA SIN ROMPER EL GRAFO COMPUTACIONAL
                state = {k: v.detach() for k, v in state.items()}
                loss_chunk = torch.tensor(0.0, device=device)

                for t in range(start, end):
                    x_t    = b_events[:, t].to(device)
                    target = b_torques[:, t + d_shift].to(device)
                    
                    if train and t > 0:
                        state['prev_torque'] = b_torques[:, t - 1 + d_shift].to(device).detach()
                    
                    pred_torque, state = model(x_t, state)

                    # Calculamos el error base
                    raw_loss = criterion(pred_torque, target)
                    
                    # Le damos hasta x3 de importancia a los torques grandes
                    weight = 1.0 + 50.0 * torch.abs(target)
                    
                    # Acumulamos el error ponderado en lugar del simple
                    loss_chunk = loss_chunk + torch.mean(raw_loss * weight)

                    #loss_chunk = loss_chunk + criterion(pred_torque, target)

                loss_chunk /= (end - start)
                accumulated_chunks.append(loss_chunk)

            if not accumulated_chunks:
                continue

            loss_episode = sum(accumulated_chunks) / len(accumulated_chunks)
                
                
            if train:
                loss_episode.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), cfg['grad_clip'])
                optimizer.step()
            
            # Promediamos el error de este bloque de episodios
            avg_loss = loss_episode.item()
            total_loss += avg_loss
            batches += 1
            pbar.set_postfix({'loss': f'{avg_loss:.4f}'})

    return total_loss / batches


def train():
    device = torch.device('mps')
    print(f"Device: {device}  (input_size: {CONFIG['input_size']}×{CONFIG['input_size']})")

    stats = load_stats(CONFIG['data_dir'])
    print(f"\nNormalisation stats loaded from {CONFIG['data_dir']}/dataset_stats.npz")
    print(f"  torque_std = {stats['torque_std']}")

    dl_train, dl_val = build_dataloaders(CONFIG, stats)

    model = SpikingSatelliteController(
        num_steps=CONFIG['num_steps'],
        hidden_gru=CONFIG['hidden_gru'],
        learn_beta=True,
    ).to(device)

    # --- CARGAR LOS PESOS ANTES DEL OPTIMIZADOR ---
    if CONFIG['re-train']:
        import shutil
        best_path = os.path.join(CONFIG['weights_dir'], 'best_model.pth')
        original_path = os.path.join(CONFIG['weights_dir'], 'original_model.pth')
        
        # 1. Proteger el modelo original: Si existe best_model pero no original_model, lo copiamos
        if os.path.exists(best_path) and not os.path.exists(original_path):
            shutil.copy(best_path, original_path)
            print(f"\n[INFO] Copia de seguridad creada: {original_path}")
            
        # 2. Elegir de dónde cargamos (priorizando siempre el original como base limpia)
        load_path = original_path if os.path.exists(original_path) else best_path
        
        if os.path.exists(load_path):
            print(f"\n[INFO] Reanudando entrenamiento (Fine-Tuning) desde: {load_path}")
            model.load_state_dict(torch.load(load_path, map_location=device))
        else:
            print("\n[INFO] No se encontró ningún modelo previo. Iniciando desde cero.")
    # -----------------------------------------------------

    optimizer = optim.AdamW(model.parameters(),
                            lr=CONFIG['lr'],
                            weight_decay=CONFIG['weight_decay'])
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='min', factor=0.5, patience=3
    )
    criterion = nn.MSELoss(reduction='none')
    #criterion = nn.SmoothL1Loss()

    os.makedirs(CONFIG['weights_dir'], exist_ok=True)
    best_val   = float('inf')
    no_improve = 0
    prev_lr    = CONFIG['lr']

    print(f"\nStarting training — {CONFIG['epochs']} epochs\n{'='*55}")

    for epoch in range(1, CONFIG['epochs'] + 1):
        tr_loss = run_epoch(model, dl_train, optimizer, criterion,
                                        CONFIG, device, train=True)
        vl_loss = run_epoch(model, dl_val,   optimizer, criterion,
                                        CONFIG, device, train=False)

        scheduler.step(vl_loss)

        current_lr = optimizer.param_groups[0]['lr']
        if current_lr < prev_lr:
            print(f"  → LR reducido a {current_lr:.2e}")
            prev_lr = current_lr

        flag = ''
        if vl_loss < best_val:
            best_val   = vl_loss
            no_improve = 0
            ckpt = os.path.join(CONFIG['weights_dir'], 'best_model.pth')
            torch.save(model.state_dict(), ckpt)
            flag = ' ← best'
        else:
            no_improve += 1

        print(f"Epoch {epoch:03d}/{CONFIG['epochs']} | "
              f"Train Loss: {tr_loss:.6f} | "
              f"Val Loss: {vl_loss:.6f}{flag}")

        if no_improve >= CONFIG['patience']:
            print(f"\nEarly stopping — no improvement for {CONFIG['patience']} epochs.")
            break

    print(f"\nTraining complete. Best val loss: {best_val:.4f}")
    print(f"Weights saved to: {CONFIG['weights_dir']}/best_model.pth")


if __name__ == '__main__':
    train()
