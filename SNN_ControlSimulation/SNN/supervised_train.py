    ds_train = EpisodeDataset(pairs_train, cfg['input_size'], stats)
    ds_val   = EpisodeDataset(pairs_val,   cfg['input_size'], stats)

    dl_train = DataLoader(ds_train, batch_size=cfg['batch_size'],
                          shuffle=True,  drop_last=True,  num_workers=cfg['num_workers'])
    dl_val   = DataLoader(ds_val,   batch_size=cfg['batch_size'],
                          shuffle=False, drop_last=False, num_workers=cfg['num_workers'])
    return dl_train, dl_val
